namespace ClassHub.Core.Infrastructure.Files;

/// <summary>
/// A stored file of a workspace (tenant-owned). The bytes live in <see cref="IFileStorage"/> under
/// <see cref="StorageKey"/>; files are never served from wwwroot, only through authorized endpoints.
/// </summary>
public sealed class StoredFile : ITenantOwned
{
    public const int ContentTypeMaxLength = 100;
    public const int PurposeMaxLength = 50;
    public const int StorageKeyMaxLength = 300;

    public Guid Id { get; set; }

    public Guid WorkspaceId { get; set; }

    /// <summary>What the file is for, for example <c>profile-photo</c>.</summary>
    public required string Purpose { get; set; }

    public required string ContentType { get; set; }

    public long SizeBytes { get; set; }

    /// <summary>Hex SHA-256 of the stored bytes (integrity, ETag).</summary>
    public required string Sha256 { get; set; }

    public required string StorageKey { get; set; }

    public int? Width { get; set; }

    public int? Height { get; set; }

    public DateTime CreatedAtUtc { get; set; }
}

internal sealed class StoredFileConfiguration : IEntityTypeConfiguration<StoredFile>
{
    public void Configure(EntityTypeBuilder<StoredFile> builder)
    {
        builder.ToTable("StoredFiles");
        builder.HasKey(x => x.Id);
        // Principal key for composite tenant foreign keys from other tenant-owned rows.
        builder.HasAlternateKey(x => new { x.WorkspaceId, x.Id });
        builder.Property(x => x.Purpose).HasMaxLength(StoredFile.PurposeMaxLength).IsUnicode(false).IsRequired();
        builder.Property(x => x.ContentType).HasMaxLength(StoredFile.ContentTypeMaxLength).IsUnicode(false).IsRequired();
        builder.Property(x => x.Sha256).HasMaxLength(64).IsFixedLength().IsUnicode(false).IsRequired();
        builder.Property(x => x.StorageKey).HasMaxLength(StoredFile.StorageKeyMaxLength).IsUnicode(false).IsRequired();
        builder.HasIndex(x => x.StorageKey).IsUnique();
    }
}

/// <summary>Blob storage for uploaded files. Local disk now; object storage (R2) with hosting.</summary>
public interface IFileStorage
{
    Task WriteAsync(string key, ReadOnlyMemory<byte> content, CancellationToken cancellationToken);

    /// <summary>The stored bytes as a stream, or null when the key does not exist.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

public sealed class FileStorageOptions
{
    public const string SectionName = "Files";

    /// <summary>Root folder for <see cref="LocalDiskFileStorage"/>; relative paths are under the content root.</summary>
    [Required]
    public string RootPath { get; set; } = "App_Data/uploads";
}

/// <summary>
/// Stores files below <see cref="FileStorageOptions.RootPath"/> (outside wwwroot). Keys are generated by the
/// application (<c>{workspaceId}/{fileId}.{ext}</c>); any key that would leave the root is refused.
/// </summary>
internal sealed class LocalDiskFileStorage(IOptions<FileStorageOptions> options, IHostEnvironment environment) : IFileStorage
{
    private readonly string _root = Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.Value.RootPath));

    public async Task WriteAsync(string key, ReadOnlyMemory<byte> content, CancellationToken cancellationToken)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        // CreateNew: a key is never overwritten (keys contain a fresh id).
        await using var stream = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await stream.WriteAsync(content, cancellationToken);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken)
    {
        var path = Resolve(key);
        Stream? stream = File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true)
            : null;
        return Task.FromResult(stream);
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken)
    {
        var path = Resolve(key);
        if (File.Exists(path))
        {
            File.Delete(path);
        }

        return Task.CompletedTask;
    }

    internal string Resolve(string key)
    {
        if (string.IsNullOrWhiteSpace(key) || Path.IsPathRooted(key) || key.Contains("..", StringComparison.Ordinal))
        {
            throw new ArgumentException("Invalid storage key.", nameof(key));
        }

        var path = Path.GetFullPath(Path.Combine(_root, key));
        if (!path.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new ArgumentException("Invalid storage key.", nameof(key));
        }

        return path;
    }
}

public static class FilesServiceCollectionExtensions
{
    /// <summary>Registers <see cref="IFileStorage"/> (local disk, validated options). Safe to call more than once.</summary>
    public static IServiceCollection AddClassHubFiles(this IServiceCollection services, IConfiguration configuration)
    {
        services.AddOptions<FileStorageOptions>()
            .Bind(configuration.GetSection(FileStorageOptions.SectionName))
            .ValidateDataAnnotations()
            .ValidateOnStart();
        services.TryAddSingleton<IFileStorage, LocalDiskFileStorage>();
        return services;
    }
}
